  /**
   * [รูปแบบที่ 1: Q.choice] ข้อเลือกตอบ (ปรนัย 4 ตัวเลือก)
   * เหมาะสำหรับ: นิยาม, ความเข้าใจ, เลือกสมการหรือผลลัพธ์ที่ถูกต้อง
   */
  function qChoice(R) {
    const a = R.int(2, 6);
    const n = R.int(2, 5);
    const ans = Math.pow(a, n);
    const wrongs = [
      Math.pow(a, n - 1),
      Math.pow(a, n + 1),
      a * n
    ];
    // answer คือ index ของตัวเลือกที่ถูกใน options ก่อนที่ระบบจะสลับลำดับอัตโนมัติ
    return Q.choice({
      q: `ค่าของ $${a}^{${n}}$ มีค่าเท่ากับข้อใด`,
      options: [
        `$${ans}$`,
        `$${wrongs[0]}$`,
        `$${wrongs[1]}$`,
        `$${wrongs[2]}$`
      ],
      answer: 0, // ชี้ไปที่ตัวเลือกแรก (ans)
      hint: `ให้นำ $${a}$ มาคูณกันจำนวน $${n}$ ตัว`,
      why: `$${a}^{${n}} = ${Array(n).fill(a).join(' \\times ')} = ${ans}$`,
      verify: () => 0 // selftest จะเทียบคำตอบที่เลือกกับค่าที่ verify ส่งคืน
    });
  }

  /**
   * [รูปแบบที่ 2: Q.fill] ข้อเติมคำตอบ (ตัวเลขหรือข้อความสั้น)
   * เหมาะสำหรับ: การคำนวณตัวเลข, หาพจน์, หาผลลัพธ์สุดท้าย
   */
  function qFill(R) {
    const a1 = R.int(2, 8);
    const d = R.int(3, 7);
    const n = R.int(4, 9);
    const an = a1 + (n - 1) * d;

    return Q.fill({
      q: `กำหนดลำดับเลขคณิตที่มี $a_1 = ${a1}$ และผลต่างร่วม $d = ${d}$ จงหาค่าของพจน์ที่ <b>$a_{${n}}$</b>`,
      fields: [
        {
          label: `$a_{${n}} =$`,
          answer: an,          // คำตอบที่ถูกต้อง
          unit: '',            // หน่วย (ถ้ามี เช่น 'บาท', 'คน', หรือเว้นว่าง)
          tol: 0,              // ค่าความคลาดเคลื่อนที่ยอมรับได้ (สำหรับทศนิยม)
          ph: 'พิมพ์ตัวเลข'    // placeholder ในช่องกรอก
        }
      ],
      hint: `ใช้สูตรพจน์ทั่วไปของลำดับเลขคณิต $a_n = a_1 + (n-1)d$`,
      why: `จากสูตร $a_n = a_1 + (n-1)d$<br>` +
           `แทนค่า: $a_{${n}} = ${a1} + (${n}-1)(${d}) = ${a1} + (${n - 1})(${d}) = ${an}$`,
      verify: () => an
    });
  }

  /**
   * [รูปแบบที่ 3: Q.sort] จัดกลุ่มการ์ด (Drag & Drop หรือแตะเลือกการ์ดลงกล่อง)
   * เหมาะสำหรับ: การจำแนกประเภท (เช่น ลำดับจำกัด vs ลำดับอนันต์, เลขคณิต vs เรขาคณิต)
   */
  function qSort(R) {
    const limN = R.int(10, 50);
    return Q.sort({
      q: `ลากการ์ดข้อความด้านล่างไปวางในกลุ่มที่ถูกต้อง`,
      bins: [
        { id: 'fin', label: 'ลำดับจำกัด' },
        { id: 'inf', label: 'ลำดับอนันต์' }
      ],
      items: [
        { html: `$1, 2, 3, \\dots, ${limN}$`, bin: 'fin' },
        { html: `$a_n = 2n + 1$ เมื่อ $n \\in \\{1, 2, 3, 4\\}$`, bin: 'fin' },
        { html: `$2, 4, 8, 16, \\dots$`, bin: 'inf' },
        { html: `$a_n = 3n - 5$ เมื่อ $n$ เป็นจำนวนนับ`, bin: 'inf' }
      ],
      hint: `ลำดับที่มีจำนวนพจน์แน่นอนคือลำดับจำกัด ส่วนลำดับที่มีพจน์ต่อไปได้เรื่อย ๆ ไม่สิ้นสุดคือลำดับอนันต์`,
      why: `ลำดับที่ระบุพจน์สุดท้ายหรือกำหนดขอบเขต $n$ แน่นอนเป็น <b>ลำดับจำกัด</b> ส่วนลำดับที่มีเครื่องหมาย $\\dots$ ต่อท้ายโดยไม่มีพจน์สุดท้ายเป็น <b>ลำดับอนันต์</b>`
    });
  }

  /**
   * [รูปแบบที่ 4: Q.pairs] จับคู่ 1 ต่อ 1 (Matching pairs)
   * เหมาะสำหรับ: จับคู่สูตรกับนิยาม, จับคู่ฟังก์ชันกับกราฟ, จับคู่โจทย์กับคำตอบ
   */
  function qPairs(R) {
    const a = R.int(2, 5);
    const b = R.int(2, 5);
    const sum = a + b;
    const diff = a - b;
    const prod = a * b;

    return Q.pairs({
      q: `จับคู่นิพจน์ทางซ้ายมือกับผลลัพธ์ที่ถูกต้องทางขวามือ`,
      left: [
        { key: 'p1', html: `$${a} + ${b}$` },
        { key: 'p2', html: `$${a} - ${b}$` },
        { key: 'p3', html: `$${a} \\times ${b}$` }
      ],
      chips: [
        { key: 'p1', html: `$${sum}$` },
        { key: 'p2', html: `$${diff}$` },
        { key: 'p3', html: `$${prod}$` }
      ],
      hint: `คำนวณผลลัพธ์แต่ละคู่แล้วลากไปวางในช่องที่ตรงกัน`,
      why: `$${a} + ${b} = ${sum}$, $${a} - ${b} = ${diff}$, $${a} \\times ${b} = ${prod}$`
    });
  }

  /**
   * [รูปแบบที่ 5: Q.order] เรียงลำดับขั้นตอนและเลือกเหตุผล (Proof / Step Ordering)
   * เหมาะสำหรับ: การพิสูจน์ทางคณิตศาสตร์, แสดงวิธีทำตามลำดับขั้นตอน
   */
  function qOrder(R) {
    const a = R.int(2, 5);
    const b = R.int(3, 8);
    const c = a * R.int(2, 6) + b;
    const ans = (c - b) / a;

    return Q.order({
      q: `เรียงลำดับขั้นตอนการแก้สมการ $${a}x + ${b} = ${c}$ ให้ถูกต้อง พร้อมเลือกเหตุผลกำกับ`,
      steps: [
        { html: `จากสมการเริ่มต้น $${a}x + ${b} = ${c}$`, reason: 0 },
        { html: `$${a}x = ${c} - ${b} = ${c - b}$`, reason: 1 },
        { html: `$x = \\frac{${c - b}}{${a}} = ${ans}$`, reason: 2 }
      ],
      reasons: [
        'กำหนดให้จากโจทย์',
        'สมบัติการเท่ากันของการลบ (ย้ายค่าคงตัวไปลบ)',
        'สมบัติการเท่ากันของการหาร (หารด้วยสัมประสิทธิ์หน้า x)'
      ],
      hint: `เริ่มจากโจทย์ ย้ายตัวเลขคงที่ไปลบออกก่อน แล้วจึงหารด้วยสัมประสิทธิ์หน้า $x$`,
      why: `ขั้นตอนการแก้สมการเชิงเส้นตัวแปรเดียวต้องกำจัดพจน์คงตัวก่อน แล้วจึงหาค่าตัวแปร`
    });
  }

  /**
   * [รูปแบบที่ 6: Q.find] จับผิดวิธีทำ (Find the Error)
   * เหมาะสำหรับ: ด่านพัฒนาทักษะกระบวนการ (P), วิเคราะห์ข้อผิดพลาดที่พบบ่อย
   */
  function qFind(R) {
    return Q.find({
      q: `พิจารณาการแสดงวิธีทำต่อไปนี้ แล้วระบุบรรทัดที่ผิด สาเหตุ และคำตอบที่ถูกต้อง`,
      lines: [
        `บรรทัดที่ 1: กำหนดสมการ $(x + 3)^2 = 25$`,
        `บรรทัดที่ 2: ถอดรากที่สองทั้งสองข้าง จะได้ $x + 3 = 5$ เท่านั้น`,
        `บรรทัดที่ 3: จะได้คำตอบ $x = 2$ เพียงค่าเดียว`
      ],
      wrong: 1, // บรรทัดที่ผิดคือ index 1 (บรรทัดที่ 2)
      causes: [
        'ลืมคิดกรณีคำตอบที่เป็นลบจากการถอดรากที่สอง (ต้องเป็น $\\pm 5$)',
        'กระจายกำลังสองผิดพลาด',
        'ย้ายข้างเครื่องหมายบวกลบผิด'
      ],
      cause: 0, // สาเหตุที่ผิดคือ index 0
      fixLabel: 'คำตอบที่ถูกต้องของ $x$ มี 2 ค่าคือ $2$ และจำนวนใด',
      fix: { answer: -8, tol: 0, ph: 'พิมพ์ตัวเลข' },
      hint: `การถอดรากที่สองของ $25$ จะได้ทั้ง $+5$ และ $-5$`,
      why: `เพราะ $(-5)^2 = 25$ ด้วย ดังนั้น $x + 3 = -5 \\implies x = -8$`
    });
  }

  /**
   * [รูปแบบที่ 7: Q.group] สถานการณ์ต่อเนื่องหลายข้อย่อย (Story / Multi-part)
   * เหมาะสำหรับ: โจทย์ปัญหาประยุกต์, แบบจำลองทางคณิตศาสตร์ในชีวิตจริง
   */
  function qGroup(R) {
    const salary = R.int(20, 45) * 1000;
    const expense = salary * 0.5; // หักค่าใช้จ่าย 50%
    const allowance = 60000;      // ค่าลดหย่อนส่วนตัว

    return Q.group({
      story: `<b>สถานการณ์จำลอง: การคำนวณภาษีเงินได้บุคคลธรรมดา</b><br>` +
             `นายสมมติมีเงินได้พึงประเมินตลอดปีรวม <b>${salary.toLocaleString()} บาท</b>`,
      parts: [
        Q.fill({
          label: 'ขั้นที่ 1 · ค่าใช้จ่าย 50% (ไม่เกิน 100,000 บาท)',
          q: `หักค่าใช้จ่ายได้กี่บาท`,
          answer: Math.min(expense, 100000),
          unit: 'บาท',
          why: `เงินได้ ${salary.toLocaleString()} × 50% = ${expense.toLocaleString()} บาท (ไม่เกินเพดาน 100,000 บาท)`,
          weight: 1
        }),
        Q.fill({
          label: 'ขั้นที่ 2 · เงินได้สุทธิ',
          q: `หากหักค่าลดหย่อนส่วนตัว 60,000 บาท นายสมมติจะเหลือเงินได้สุทธิเท่าใด`,
          answer: salary - Math.min(expense, 100000) - allowance,
          unit: 'บาท',
          why: `เงินได้สุทธิ = เงินได้พึงประเมิน - ค่าใช้จ่าย - ค่าลดหย่อน`,
          weight: 1
        })
      ]
    });
  }

