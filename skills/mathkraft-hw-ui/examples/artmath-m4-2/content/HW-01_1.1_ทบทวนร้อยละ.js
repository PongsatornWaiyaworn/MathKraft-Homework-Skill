/* HW-01 · 1.1 ทบทวนร้อยละ */
(function () {
  'use strict';
  const MK = window.MK, Q = MK.Q;
  const vat = 7;

  function r2(n) { return Math.round((n + Number.EPSILON) * 100) / 100; }
  function fmt(n, d) { return Number(n).toLocaleString('en-US', { minimumFractionDigits: d, maximumFractionDigits: d }); }
  function baht(n) { n = r2(n); return Number.isInteger(n) ? fmt(n, 0) : fmt(n, 2); }
  function step(R, a, b, s) { return a + s * R.int(0, Math.floor((b - a) / s)); }

  window.HW = {
    id: 'HW-01', unit: 1, unitName: 'หน่วยที่ 1 ภาษีมูลค่าเพิ่ม', title: 'ทบทวนร้อยละ',
    sub: 'ทบทวนการคิดร้อยละของจำนวน เป็นร้อยละเท่าใด และการเพิ่ม/ลดราคา เพื่อเป็นพื้นฐานสำคัญในการคำนวณภาษีมูลค่าเพิ่ม (VAT)',
    size: '6 ข้อ · 10 นาที', K: 3, P: 0,
    levels: [
      {
        short: 'ด่าน 1', title: 'ด่าน 1 · พื้นฐานร้อยละ', kind: 'K', points: 1.5,
        skill: 'คิดร้อยละของจำนวนและหาร้อยละจากส่วน',
        desc: 'หาค่าร้อยละของจำนวน และหาว่าคิดเป็นร้อยละเท่าใดของทั้งหมด',
        intro: 'พิมพ์คำตอบเป็นตัวเลข (ทศนิยม 2 ตำแหน่งถ้าไม่ลงตัว) ตอบถูกครั้งแรกได้คะแนนเต็ม',
        build(R) {
          // 1) ร้อยละของจำนวน
          const p1 = R.pick([8, 12, 15, 18, 24, 35]);
          const M1 = step(R, 1000, 6000, 50);
          const ans1 = M1 * p1 / 100;
          const q1 = Q.fill({
            label: 'ข้อ 1',
            q: `โรงเรียนมอบทุนช่วยค่าวัสดุศิลปะ <b>${p1}%</b> ของค่าวัสดุทั้งหมด <b>${baht(M1)} บาท</b> นักเรียนจะได้รับทุนกี่บาท`,
            answer: ans1, unit: 'บาท',
            hint: 'ร้อยละ = ส่วนใน 100 ส่วน ต้องคูณด้วย p/100',
            why: `${p1}% ของ ${baht(M1)} = ${p1}/100 × ${baht(M1)} = <b>${baht(ans1)} บาท</b>`,
            verify: () => M1 * p1 / 100
          });

          // 2) เป็นร้อยละเท่าใดของอีกจำนวน
          let T2, pc2, s2;
          do {
            T2 = R.pick([80, 120, 160, 200, 250, 400]);
            pc2 = R.pick([12.5, 15, 22.5, 35, 37.5, 45, 60, 62.5, 72.5, 85]);
            s2 = T2 * pc2 / 100;
          } while (!Number.isInteger(s2));
          const q2 = Q.fill({
            label: 'ข้อ 2',
            q: `ร้านขายผ้าใบมีผ้าใบ <b>${T2} ผืน</b> ขายได้แล้ว <b>${s2} ผืน</b> ขายได้คิดเป็นร้อยละเท่าใดของผ้าใบทั้งหมด`,
            answer: pc2, unit: '%',
            hint: 'ร้อยละ = (ส่วนที่ต้องการ ÷ ทั้งหมด) × 100',
            why: `ร้อยละ = (ส่วนที่ต้องการ ÷ ทั้งหมด) × 100 = ${s2}/${T2} × 100 = <b>${pc2}%</b>`,
            verify: () => pc2
          });

          // 3) หาจำนวนทั้งหมดเมื่อทราบร้อยละ
          const p3 = R.pick([10, 15, 20, 25, 30, 40]);
          const N3 = step(R, 600, 4000, 100);
          const d3 = N3 * p3 / 100;
          const q3 = Q.fill({
            label: 'ข้อ 3',
            q: `สีโปสเตอร์ชุดหนึ่งลดราคาไป <b>${baht(d3)} บาท</b> ซึ่งคิดเป็น <b>${p3}%</b> ของราคาป้ายเดิม ราคาป้ายเดิมกี่บาท`,
            answer: N3, unit: 'บาท',
            hint: 'โจทย์ให้ส่วนลด แล้วหาทั้งหมด ต้องหารด้วย p/100 (คือคูณ 100/p)',
            why: `ให้ราคาเดิม N บาท จะได้ ${p3}/100 × N = ${baht(d3)} → N = ${baht(d3)} × 100/${p3} = <b>${baht(N3)} บาท</b>`,
            verify: () => N3
          });

          return [q1, q2, q3];
        }
      },
      {
        short: 'ด่าน 2', title: 'ด่าน 2 · การเพิ่มและลดราคา', kind: 'K', points: 1.5,
        skill: 'คำนวณราคาสินค้าหลังลดราคาและหลังบวก VAT 7%',
        desc: 'คำนวณราคาหลังลด 15%, บวก VAT 7%, และย้อนหาราคาก่อนรวม VAT',
        intro: 'พิมพ์คำตอบเป็นตัวเลข ระวังความแตกต่างระหว่าง "ฐานราคาก่อนบวก" กับ "ฐานราคาหลังบวก"',
        build(R) {
          // 4) ลดราคา 15%
          let P4;
          do { P4 = step(R, 600, 3000, 20); } while (P4 === 1200);
          const ans4 = P4 * 0.85;
          const q4 = Q.fill({
            label: 'ข้อ 4',
            q: `ชุดพู่กันเบอร์พิเศษติดป้ายราคา <b>${baht(P4)} บาท</b> ร้านประกาศ “ลดราคา <b>15%</b>” ต้องจ่ายเงินกี่บาท`,
            answer: ans4, unit: 'บาท',
            hint: 'ลดลง 15% จะเหลือ 100 − 15 = 85% ของราคาเดิม',
            why: `ลดลง 15% จะเหลือ 100 − 15 = 85% ของราคาเดิม → ต้องจ่าย ${baht(P4)} × 85/100 = <b>${baht(ans4)} บาท</b>`,
            verify: () => P4 * 0.85
          });

          // 5) บวกเพิ่ม 7%
          let P5;
          do { P5 = step(R, 400, 3000, 50); } while (P5 === 2500);
          const ans5 = P5 * (100 + vat) / 100;
          const q5 = Q.fill({
            label: 'ข้อ 5',
            q: `ขาตั้งวาดภาพราคา <b>${baht(P5)} บาท</b> ต้องบวกเพิ่มอีก <b>${vat}%</b> จะต้องจ่ายทั้งหมดกี่บาท`,
            answer: ans5, unit: 'บาท',
            hint: `เพิ่มขึ้น ${vat}% จะเป็น ${100 + vat}% ของราคาเดิม`,
            why: `เพิ่มขึ้น ${vat}% จะเป็น 100 + ${vat} = ${100 + vat}% ของราคาเดิม → ต้องจ่าย ${baht(P5)} × ${100 + vat}/100 = <b>${baht(ans5)} บาท</b>`,
            verify: () => P5 * (100 + vat) / 100
          });

          // 6) ย้อนหาราคาก่อนบวกเพิ่ม 7%
          let B6;
          do { B6 = step(R, 1200, 6000, 100); } while (B6 === 4000);
          const N6 = B6 * (100 + vat) / 100;
          const q6 = Q.fill({
            label: 'ข้อ 6',
            q: `ราคาสินค้าหลังบวกเพิ่ม ${vat}% แล้วเท่ากับ <b>${baht(N6)} บาท</b> ราคาก่อนบวกเพิ่มเท่ากับกี่บาท`,
            answer: B6, unit: 'บาท',
            hint: `ให้ราคาเดิม N บาท จะได้ N × ${100 + vat}/100 = ราคาใหม่ → N = ราคาใหม่ × 100/${100 + vat}`,
            why: `ให้ราคาเดิม N บาท จะได้ N × ${100 + vat}/100 = ${baht(N6)} → N = ${baht(N6)} × 100/${100 + vat} = <b>${baht(B6)} บาท</b><br><small class="muted">ตรวจ: ${baht(B6)} × 1.0${vat} = ${baht(N6)} ✓</small>`,
            verify: () => B6
          });

          return [q4, q5, q6];
        }
      }
    ]
  };
})();
