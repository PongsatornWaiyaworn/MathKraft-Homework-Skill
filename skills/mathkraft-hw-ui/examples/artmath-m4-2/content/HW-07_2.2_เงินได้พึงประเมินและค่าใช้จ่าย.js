/* HW-07 · 2.2 เงินได้พึงประเมินและการหักค่าใช้จ่าย */
(function () {
  'use strict';
  const MK = window.MK, Q = MK.Q;
  const pct = 50, cap = 100000, p60 = 60;

  function r2(n) { return Math.round((n + Number.EPSILON) * 100) / 100; }
  function fmt(n, d) { return Number(n).toLocaleString('en-US', { minimumFractionDigits: d, maximumFractionDigits: d }); }
  function baht(n) { n = r2(n); return Number.isInteger(n) ? fmt(n, 0) : fmt(n, 2); }
  function step(R, a, b, s) { return a + s * R.int(0, Math.floor((b - a) / s)); }

  window.HW = {
    id: 'HW-07', unit: 2, unitName: 'หน่วยที่ 2 ภาษีเงินได้บุคคลธรรมดา', title: 'เงินได้พึงประเมินและการหักค่าใช้จ่าย',
    sub: 'คำนวณเงินได้พึงประเมินทั้งปีและการหักค่าใช้จ่ายตามกฎหมาย: เงินเดือนและฟรีแลนซ์ 40(1)+(2) หักได้ 50% สูงสุดไม่เกิน 100,000 บาท และการค้าขาย 40(8) หักเป็นการเหมา 60%',
    size: '6 ข้อ · 12 นาที', K: 3, P: 0,
    levels: [
      {
        short: 'ด่าน 1', title: 'ด่าน 1 · เงินเดือนและค่าจ้าง 40(1)', kind: 'K', points: 1.5,
        skill: 'คำนวณเงินได้ทั้งปีและค่าใช้จ่ายของเงินเดือนและโบนัส (มีเพดาน 100,000 บาท)',
        desc: 'คำนวณเงินได้พึงประเมินทั้งปีและค่าใช้จ่ายที่หักได้ 3 ข้อ',
        intro: 'เงินได้ 40(1) และ 40(2) หักค่าใช้จ่ายเป็นการเหมาได้ 50% แต่รวมกันไม่เกิน 100,000 บาท',
        build(R) {
          const nm = R.sample(['คุณใบบัว', 'คุณธันวา', 'คุณมะปราง', 'คุณกวิน', 'คุณพิมพ์', 'คุณนที'], 3);
          const qs = [];

          // ข้อ 1: เงินเดือนอย่างเดียว (ไม่เกินเพดาน 100,000)
          {
            const m = step(R, 12000, 16000, 500);
            const inc = m * 12;
            const exp = inc * pct / 100;
            qs.push(Q.fill({
              label: 'ข้อ 1',
              q: `<b>${nm[0]}</b> มีเงินได้จากเงินเดือนเดือนละ <b>${baht(m)} บาท</b> ตลอดทั้งปี ไม่มีรายได้อื่น`,
              fields: [
                { label: 'เงินได้พึงประเมินทั้งปี', answer: inc, unit: 'บาท', tol: 0.01 },
                { label: 'ค่าใช้จ่ายที่หักได้ (50%)', answer: exp, unit: 'บาท', tol: 0.01 }
              ],
              why: `เงินได้ทั้งปี = ${baht(m)} × 12 = <b>${baht(inc)} บาท</b><br>หักค่าใช้จ่าย 50% = ${baht(inc)} × 50/100 = <b>${baht(exp)} บาท</b> (ไม่เกินเพดาน 100,000 บาท)`,
              verify: () => [inc, exp]
            }));
          }

          // ข้อ 2: เงินเดือนสูง (ชนเพดาน 100,000 บาท)
          {
            const m = step(R, 25000, 60000, 2500);
            const inc = m * 12;
            const exp = cap;
            qs.push(Q.fill({
              label: 'ข้อ 2',
              q: `<b>${nm[1]}</b> มีเงินได้จากเงินเดือนเดือนละ <b>${baht(m)} บาท</b> ตลอดทั้งปี ไม่มีรายได้อื่น`,
              fields: [
                { label: 'เงินได้พึงประเมินทั้งปี', answer: inc, unit: 'บาท', tol: 0.01 },
                { label: 'ค่าใช้จ่ายที่หักได้ (สูงสุดไม่เกินเพดาน)', answer: exp, unit: 'บาท', tol: 0.01 }
              ],
              why: `เงินได้ทั้งปี = ${baht(m)} × 12 = <b>${baht(inc)} บาท</b><br>50% ของเงินได้คือ ${baht(inc * 0.5)} บาท แต่กฎหมายกำหนดเพดานสูงสุดไม่เกิน 100,000 บาท → หักได้ <b>${baht(cap)} บาท</b>`,
              verify: () => [inc, exp]
            }));
          }

          // ข้อ 3: เงินเดือน + โบนัส (รวมเป็น 40(1))
          {
            const m = step(R, 20000, 35000, 1000);
            const bMonths = R.pick([1, 2, 3]);
            const bonus = m * bMonths;
            const inc = m * 12 + bonus;
            const exp = Math.min(inc * pct / 100, cap);
            qs.push(Q.fill({
              label: 'ข้อ 3',
              q: `<b>${nm[2]}</b> ได้รับเงินเดือนเดือนละ <b>${baht(m)} บาท</b> และได้รับเงินโบนัสปลายปีอีก <b>${bMonths} เท่าของเงินเดือน</b> (${baht(bonus)} บาท)`,
              fields: [
                { label: 'เงินได้พึงประเมินทั้งปี', answer: inc, unit: 'บาท', tol: 0.01 },
                { label: 'ค่าใช้จ่ายที่หักได้', answer: exp, unit: 'บาท', tol: 0.01 }
              ],
              why: `เงินได้ทั้งปี = (${baht(m)} × 12) + ${baht(bonus)} = <b>${baht(inc)} บาท</b><br>ค่าใช้จ่ายหักได้ 50% ไม่เกิน 100,000 บาท → หักได้ <b>${baht(exp)} บาท</b>`,
              verify: () => [inc, exp]
            }));
          }

          return qs;
        }
      },
      {
        short: 'ด่าน 2', title: 'ด่าน 2 · ฟรีแลนซ์และค้าขาย 40(2), 40(8)', kind: 'K', points: 1.5,
        skill: 'คำนวณค่าใช้จ่ายเงินได้รวม 40(1)+(2) และเงินได้จากการค้าขาย 40(8)',
        desc: 'คำนวณเงินได้พึงประเมินและค่าใช้จ่ายของฟรีแลนซ์และพ่อค้าแม่ค้าออนไลน์ 3 ข้อ',
        intro: 'เงินได้ 40(1) และ 40(2) ต้องนับเพดาน 100,000 บาทร่วมกัน · เงินได้ 40(8) ขายของหักเหมาได้ 60% ไม่จำกัดเพดาน 100,000',
        build(R) {
          const nm = R.sample(['คุณขวัญ', 'คุณปัณณ์', 'คุณอรุณ', 'คุณเมฆ'], 3);
          const qs = [];

          // ข้อ 4: เงินเดือน 40(1) + ค่างานฟรีแลนซ์ 40(2) นับเพดานร่วมกัน
          {
            const m = step(R, 15000, 25000, 1000);
            const free = step(R, 30000, 90000, 10000);
            const inc = m * 12 + free;
            const exp = Math.min(inc * pct / 100, cap);
            qs.push(Q.fill({
              label: 'ข้อ 4',
              q: `<b>${nm[0]}</b> มีเงินเดือนรวมทั้งปี <b>${baht(m * 12)} บาท</b> และรับงานฟรีแลนซ์ออกแบบกราฟิกระหว่างปีได้เงินอีก <b>${baht(free)} บาท</b>`,
              fields: [
                { label: 'เงินได้พึงประเมินทั้งปี (40(1) + 40(2))', answer: inc, unit: 'บาท', tol: 0.01 },
                { label: 'ค่าใช้จ่ายที่หักได้ (นับเพดานรวมกัน)', answer: exp, unit: 'บาท', tol: 0.01 }
              ],
              why: `เงินได้ทั้งปี = ${baht(m * 12)} + ${baht(free)} = <b>${baht(inc)} บาท</b><br>40(1) และ 40(2) กฎหมายให้นับเพดานรวมกัน 50% ไม่เกิน 100,000 บาท → หักได้ <b>${baht(exp)} บาท</b>`,
              verify: () => [inc, exp]
            }));
          }

          // ข้อ 5: ค้าขายออนไลน์ 40(8) หักเหมา 60%
          {
            const rev = step(R, 300000, 800000, 50000);
            const exp = rev * p60 / 100;
            qs.push(Q.fill({
              label: 'ข้อ 5',
              q: `<b>${nm[1]}</b> ขายเสื้อผ้าและงานสกรีนออนไลน์ ตลอดปีมียอดขายรวม (เงินได้ประเภท 40(8)) <b>${baht(rev)} บาท</b> (เลือกหักค่าใช้จ่ายเป็นการเหมาตามกฎหมาย ${p60}%)`,
              fields: [
                { label: 'เงินได้พึงประเมินทั้งปี', answer: rev, unit: 'บาท', tol: 0.01 },
                { label: `ค่าใช้จ่ายหักเหมา (${p60}%)`, answer: exp, unit: 'บาท', tol: 0.01 }
              ],
              why: `เงินได้ทั้งปี = <b>${baht(rev)} บาท</b><br>เงินได้ 40(8) หักเหมาได้ 60% = ${baht(rev)} × 60/100 = <b>${baht(exp)} บาท</b> (ไม่มีเพดาน 100,000 บาทเหมือน 40(1))`,
              verify: () => [rev, exp]
            }));
          }

          // ข้อ 6: ค่าจ้างวิชาชีพอิสระ หรือ ฟรีแลนซ์อย่างเดียว
          {
            const freeOnly = step(R, 180000, 420000, 20000);
            const exp = Math.min(freeOnly * pct / 100, cap);
            qs.push(Q.fill({
              label: 'ข้อ 6',
              q: `<b>${nm[2]}</b> เป็นช่างภาพอิสระ รับงานถ่ายภาพตลอดทั้งปี (เงินได้ประเภท 40(2)) รวมเป็นเงิน <b>${baht(freeOnly)} บาท</b> ไม่มีเงินเดือน`,
              fields: [
                { label: 'เงินได้พึงประเมินทั้งปี', answer: freeOnly, unit: 'บาท', tol: 0.01 },
                { label: 'ค่าใช้จ่ายที่หักได้', answer: exp, unit: 'บาท', tol: 0.01 }
              ],
              why: `เงินได้ทั้งปี = <b>${baht(freeOnly)} บาท</b><br>เงินได้ 40(2) หักค่าใช้จ่ายได้ 50% ไม่เกิน 100,000 บาท → หักได้ <b>${baht(exp)} บาท</b>`,
              verify: () => [freeOnly, exp]
            }));
          }

          return qs;
        }
      }
    ]
  };
})();
