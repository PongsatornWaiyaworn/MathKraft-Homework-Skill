  /* ---------- level 2 : mixed counting ---------- */
  function qChooseAssign(R) {
    const n = R.int(7, 10), k = R.int(3, 4);
    const ans = C(n, k) * P(k, 2);
    return Q.fill({ q: r`ชมรมมีสมาชิก <b>${n} คน</b> ต้องเลือกคณะทำงาน <b>${k} คน</b> แล้วเลือกจากคณะทำงานที่ได้ ให้ดำรงตำแหน่ง <b>หัวหน้า</b> และ <b>รองหัวหน้า</b> (คนละตำแหน่ง) ทำได้กี่วิธี`,
      answer: ans, unit: 'วิธี', hint: r`ทำสองขั้นตอนต่อเนื่อง: ขั้นแรกลำดับไม่สำคัญ ขั้นที่สองลำดับสำคัญ แล้วนำมาคูณกัน`,
      why: r`ขั้นที่ 1: \(C(${n},${k})=${C(n, k)}\) · ขั้นที่ 2: \(P(${k},2)=${P(k, 2)}\)<br>รวม \(${C(n, k)}\times ${P(k, 2)}=${ans}\) วิธี`,
      verify: () => { let c = 0; bf.eachComb([...Array(n).keys()], k, (s) => { bf.eachRPerm(s, 2, () => c++); }); return c; } });
  }
  function qLineMixed(R) {
    const n = R.int(5, 7); const [a, b, c] = R.sample(NAMES, 3);
    const ans = F(n - 1) - 2 * F(n - 2);
    return Q.fill({ q: r`นักเรียน ${n} คนเรียงแถวเดียว โดย <b>${c}</b> ต้องอยู่<b>ท้ายแถว</b> และ <b>${a}</b> กับ <b>${b}</b> <b>ต้องไม่ยืนติดกัน</b> จัดแถวได้กี่แบบ`,
      answer: ans, unit: 'แบบ', hint: r`ล็อกตำแหน่งของ ${c} ก่อน แล้วนับการจัดคนที่เหลือโดยหักกรณีที่ ${a} กับ ${b} ติดกัน`,
      why: r`${c} อยู่ท้ายแถว เหลือจัดอีก ${n - 1} คน: ทั้งหมด \(${n - 1}!=${F(n - 1)}\) · ${a}, ${b} ติดกัน \(2\times ${n - 2}!=${2 * F(n - 2)}\)<br>ไม่ติดกัน \(=${F(n - 1)}-${2 * F(n - 2)}=${ans}\) แบบ`,
      verify: () => { let cnt = 0; bf.eachPerm([...Array(n).keys()], (p) => { if (p[n - 1] === 2 && Math.abs(p.indexOf(0) - p.indexOf(1)) !== 1) cnt++; }); return cnt; } });
  }
