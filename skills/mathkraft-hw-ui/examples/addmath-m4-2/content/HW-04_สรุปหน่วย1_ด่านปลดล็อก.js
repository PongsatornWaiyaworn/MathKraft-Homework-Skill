  /* ---------- level 4 : geometry ---------- */
  function gridPaths(a, b) { // right/up steps from (0,0) to (a,b)
    const f = (x, y) => (x === a && y === b ? 1 : (x < a ? f(x + 1, y) : 0) + (y < b ? f(x, y + 1) : 0));
    return f(0, 0);
  }
  function qGrid(R) {
    const a = R.int(3, 6), b = R.int(3, 5);
    return Q.fill({ q: r`ตารางสี่เหลี่ยมมีความยาว <b>${a} หน่วย</b> และสูง <b>${b} หน่วย</b> เดินจากมุมซ้ายล่าง A ไปมุมขวาบน B โดยเดิน<b>ไปทางขวา</b>หรือ<b>ขึ้นบน</b>ทีละ 1 หน่วยเท่านั้น มีกี่เส้นทาง`,
      answer: C(a + b, a), unit: 'เส้นทาง', hint: r`ต้องเดิน ทางขวา ${a} ก้าว และขึ้นบน ${b} ก้าว รวม ${a + b} ก้าว — เลือกว่าก้าวที่เท่าไรเป็นการเดินขวา`,
      why: r`เลือกตำแหน่งของก้าว “ขวา” ${a} ก้าวจากทั้งหมด ${a + b} ก้าว → \(C(${a + b},${a})=${C(a + b, a)}\) เส้นทาง`, verify: () => gridPaths(a, b) });
  }
