      why: r`เชื่อมจุดยอดทุกคู่ \(C(${n},2)=${C(n, 2)}\) แล้วหักด้าน ${n} ด้าน → \(${C(n, 2)}-${n}=${C(n, 2) - n}\) เส้น`,
