  // brute-force helpers (used only by tests, but cheap enough to keep inline)
  function seqCount(D, L, rep, okFirst, okLast) {
    let c = 0;
    const cur = [];
    (function go(pos, used) {
      if (pos === L) { if (okFirst(cur[0]) && okLast(cur[L - 1])) c++; return; }
      for (let i = 0; i < D.length; i++) {
        if (!rep && used.has(i)) continue;
        cur[pos] = D[i]; used.add(i); go(pos + 1, used); used.delete(i);
      }
    })(0, new Set());
    return c;
  }
