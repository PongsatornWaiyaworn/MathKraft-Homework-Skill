  function qAtLeast(R) {
    const w = R.int(3, 6), d = R.int(4, 7), N = w + d, k = 3;
    const tot = C(N, k), none = C(d, k);
    return Q.fill({ q: r`ถุงมีลูกบอลสีขาว ${w} ลูก สีดำ ${d} ลูก หยิบพร้อมกัน 3 ลูกแบบสุ่ม ความน่าจะเป็นที่ได้ลูกบอล<b>สีขาวอย่างน้อย 1 ลูก</b> เท่ากับเท่าใด`,
      answer: (tot - none) / tot, prob: true, ph: PH, show: frs(tot - none, tot), hint: r`หา P(ไม่ได้สีขาวเลย) ก่อน คือหยิบสีดำทั้ง 3 ลูก แล้วนำไปลบจาก 1`,
      why: r`\(P(\text{ไม่ได้สีขาวเลย})=\dfrac{C(${d},3)}{C(${N},3)}=\dfrac{${none}}{${tot}}\) · \(P(\text{สีขาวอย่างน้อย 1})=1-\dfrac{${none}}{${tot}}=${fr(tot - none, tot)}\)`,
      verify: () => { const bl = [...Array(N).keys()]; let s = 0, t = 0; bf.eachComb(bl, k, (p) => { t++; if (p.some((x) => x < w)) s++; }); return s / t; } });
  }
