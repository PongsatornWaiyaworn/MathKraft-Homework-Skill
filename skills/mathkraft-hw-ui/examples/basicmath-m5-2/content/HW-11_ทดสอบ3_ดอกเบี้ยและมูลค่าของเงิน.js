/* HW-11 · ทดสอบ 3 ดอกเบี้ยและมูลค่าของเงิน */
(function () {
  'use strict';
  const MK = window.MK, Q = MK.Q;

  function fmtN(n, d = 2) {
    return Number(n).toLocaleString('en-US', { minimumFractionDigits: d, maximumFractionDigits: d });
  }

  window.HW = {
    id: 'HW-11', unit: 2, unitName: 'หน่วยที่ 2 ดอกเบี้ยและมูลค่าของเงิน', title: 'ทดสอบ 3 · ดอกเบี้ยและมูลค่าของเงิน',
    sub: 'ทดสอบความรู้เรื่องดอกเบี้ยคงต้น ดอกเบี้ยทบต้น อัตราดอกเบี้ยที่แท้จริง และมูลค่าปัจจุบัน (6 ข้อ 6 คะแนน)',
    size: '6 ข้อ · 20 นาที', K: 6, P: 0,
    levels: [
      {
        short: 'ตอน 1', title: 'ตอน 1 · ดอกเบี้ยคงต้นและทบต้น', kind: 'K', points: 3,
        skill: 'คำนวณเงินรวมจากดอกเบี้ยคงต้นและดอกเบี้ยทบต้นทั้งแบบรายปีและหลายครั้งต่อปี',
        desc: 'คำนวณคำตอบ 3 ข้อ (ข้อละ 1 คะแนน)',
        intro: 'ใช้สูตรดอกเบี้ยคงต้น $S = P(1+rt)$ และดอกเบี้ยทบต้น $S = P(1+i)^n$',
        build(R) {
          const qs = [];

          // ข้อ 1: ดอกเบี้ยคงต้น
          {
            const P = R.pick([20000, 30000, 40000, 50000, 60000]);
            const rr = R.pick([2, 3, 4, 5]);
            const t = R.pick([2, 3, 4, 5]);
            const I = P * (rr / 100) * t;
            const S = P + I;

            qs.push(Q.fill({
              label: 'ข้อ 1',
              q: `ฝากเงิน <b>${fmtN(P, 0)} บาท</b> ได้รับดอกเบี้ยคงต้น <b>${rr}% ต่อปี</b> เป็นเวลา <b>${t} ปี</b> จะได้เงินรวมทั้งหมดกี่บาท`,
              answer: S, unit: 'บาท', tol: 0.05,
              hint: `ใช้สูตร $I = Prt$ แล้วนำมารวมกับเงินต้น $S = P + I$`,
              why: `ดอกเบี้ย $I = ${P} \\times ${rr / 100} \\times ${t} = ${fmtN(I, 2)}$ บาท<br>เงินรวม $S = ${P} + ${I} = <b>${fmtN(S, 2)}</b>$ บาท`,
              verify: () => S
            }));
          }

          // ข้อ 2: ดอกเบี้ยทบต้น vs คงต้น
          {
            const P = R.pick([20000, 30000, 40000, 50000]);
            const rr = R.pick([2, 3, 4, 5]);
            const t = R.pick([3, 4, 5]);
            const i = rr / 100;
            const S_simple = P * (1 + i * t);
            const S_comp = P * Math.pow(1 + i, t);
            const diff = S_comp - S_simple;

            qs.push(Q.fill({
              label: 'ข้อ 2',
              q: `ฝากเงิน <b>${fmtN(P, 0)} บาท</b> อัตราดอกเบี้ย <b>${rr}% ต่อปี</b> คิดทบต้นทุกปี เป็นเวลา <b>${t} ปี</b> จงหาเงินรวมแบบทบต้น และหาว่าได้รับเงินรวมมากกว่าแบบคงต้นอยู่กี่บาท (ทศนิยม 2 ตำแหน่ง)`,
              fields: [
                { label: 'เงินรวมแบบทบต้น $=$', answer: S_comp, unit: 'บาท', tol: 0.05 },
                { label: 'มากกว่าแบบคงต้นอยู่ $=$', answer: diff, unit: 'บาท', tol: 0.05 }
              ],
              hint: `คำนวณแบบทบต้นด้วย $P(1+i)^t$ และคงต้นด้วย $P(1+rt)$ แล้วนำมาลบกัน`,
              why: `ทบต้น: $S = ${P}(1 + ${i})^{${t}} = ${fmtN(S_comp, 2)}$ บาท<br>คงต้น: $S = ${P}(1 + ${i} \\times ${t}) = ${fmtN(S_simple, 2)}$ บาท<br>ส่วนต่าง $= <b>${fmtN(diff, 2)}</b>$ บาท`,
              verify: () => [S_comp, diff]
            }));
          }

          // ข้อ 3: ทบต้นทุก 3 เดือน
          {
            const P = R.pick([15000, 25000, 35000, 50000]);
            const rr = R.pick([4, 6, 8]);
            const t = R.pick([2, 3, 4]);
            const k = 4;
            const i = rr / (100 * k);
            const n = k * t;
            const S = P * Math.pow(1 + i, n);

            qs.push(Q.fill({
              label: 'ข้อ 3',
              q: `ฝากเงิน <b>${fmtN(P, 0)} บาท</b> อัตราดอกเบี้ย <b>${rr}% ต่อปี</b> คิดดอกเบี้ยทบต้น<b>ทุก 3 เดือน</b> เป็นเวลา <b>${t} ปี</b> จงหาเงินรวมเมื่อครบกำหนด (ทศนิยม 2 ตำแหน่ง)`,
              answer: S, unit: 'บาท', tol: 0.05,
              hint: `ทบต้นทุก 3 เดือน ($k = 4$): อัตราต่องวด $i = \\frac{${rr}\\%}{4}$ และจำนวนงวด $n = 4 \\times ${t} = ${n}$ งวด`,
              why: `$i = \\frac{${rr / 100}}{4} = ${i}$, $n = 4 \\times ${t} = ${n}$<br>$S = ${P}(1 + ${i})^{${n}} = <b>${fmtN(S, 2)}</b>$ บาท`,
              verify: () => S
            }));
          }

          return qs;
        }
      },
      {
        short: 'ตอน 2', title: 'ตอน 2 · อัตราดอกเบี้ยและมูลค่าของเงิน', kind: 'K', points: 3,
        skill: 'คำนวณอัตราดอกเบี้ยที่แท้จริง มูลค่าปัจจุบัน และเปรียบเทียบข้อเสนอต่างเวลา',
        desc: 'คำนวณคำตอบ 3 ข้อ (ข้อละ 1 คะแนน)',
        intro: 'คิดวิเคราะห์ตามหลักการคณิตศาสตร์การเงิน',
        build(R) {
          const qs = [];

          // ข้อ 4: อัตราดอกเบี้ยที่แท้จริง
          {
            const rr = R.pick([3.6, 4.8, 6.0, 7.2]);
            const k = R.pick([4, 12]);
            const eff = (Math.pow(1 + (rr / 100) / k, k) - 1) * 100;

            qs.push(Q.fill({
              label: 'ข้อ 4',
              q: `ธนาคารประกาศอัตราดอกเบี้ยเงินฝาก <b>${rr}% ต่อปี</b> คิดดอกเบี้ยทบต้น<b>${k === 12 ? 'ทุกเดือน' : 'ทุก 3 เดือน'}</b> ($k = ${k}$) จงหาอัตราดอกเบี้ยที่แท้จริงต่อปี ($r_{eff}$) เป็นร้อยละ (ทศนิยม 2 ตำแหน่ง)`,
              answer: eff, unit: '%', tol: 0.05,
              hint: `ใช้สูตร $r_{eff} = \\left(1 + \\frac{r}{k}\\right)^k - 1$ คูณ 100 เพื่อทำเป็นเปอร์เซ็นต์`,
              why: `$r_{eff} = \\left(1 + \\frac{${rr / 100}}{${k}}\\right)^{${k}} - 1 \\approx <b>${fmtN(eff, 2)}%</b>$`,
              verify: () => eff
            }));
          }

          // ข้อ 5: มูลค่าปัจจุบัน
          {
            const F = R.pick([100000, 150000, 200000, 250000]);
            const rr = R.pick([3, 4, 5, 6]);
            const t = R.pick([3, 4, 5]);
            const i = rr / 100;
            const P = F / Math.pow(1 + i, t);

            qs.push(Q.fill({
              label: 'ข้อ 5',
              q: `จงหามูลค่าปัจจุบัน ($P$) ของเงิน <b>${fmtN(F, 0)} บาท</b> ที่จะได้รับในอีก <b>${t} ปี</b>ข้างหน้า ถ้าอัตราดอกเบี้ยตลาดเท่ากับ <b>${rr}% ต่อปี</b> คิดทบต้นทุกปี (ทศนิยม 2 ตำแหน่ง)`,
              answer: P, unit: 'บาท', tol: 0.1,
              hint: `ใช้สูตรมูลค่าปัจจุบัน $P = \\frac{F}{(1+i)^n} = \\frac{${F}}{(1 + ${i})^{${t}}}$`,
              why: `$P = \\frac{${F}}{(1 + ${i})^{${t}}} = <b>${fmtN(P, 2)}</b>$ บาท`,
              verify: () => P
            }));
          }

          // ข้อ 6: เปรียบเทียบข้อเสนอต่างเวลา
          {
            const X = R.pick([30000, 40000, 50000, 60000]);
            const rr = R.pick([3, 4, 5]);
            const t = R.pick([3, 4]);
            const i = rr / 100;
            const FVA = X * Math.pow(1 + i, t);
            const better = R.chance(0.5);
            const mult = better ? 1.08 : 0.92;
            const Y = Math.round(FVA * mult / 500) * 500;
            const PVB = Y / Math.pow(1 + i, t);

            const bWins = PVB > X;

            qs.push(Q.choice({
              label: 'ข้อ 6',
              q: `เลือกระหว่าง:<br>` +
                `• <b>ข้อเสนอ A:</b> รับเงินสด <b>${fmtN(X, 0)} บาท วันนี้</b><br>` +
                `• <b>ข้อเสนอ B:</b> รับเงิน <b>${fmtN(Y, 0)} บาท ในอีก ${t} ปีข้างหน้า</b><br>` +
                `กำหนดอัตราดอกเบี้ย <b>${rr}% ต่อปี</b> คิดทบต้นทุกปี ควรเลือกข้อเสนอใด`,
              options: [
                bWins
                  ? `ควรเลือก <b>ข้อเสนอ B</b> เพราะมีมูลค่าปัจจุบันประมาณ ${fmtN(PVB, 2)} บาท มากกว่าเงินสด ${fmtN(X, 0)} บาทของข้อเสนอ A`
                  : `ควรเลือก <b>ข้อเสนอ A</b> เพราะเงินสดวันนี้ ${fmtN(X, 0)} บาท มีมูลค่าปัจจุบันมากกว่าข้อเสนอ B (${fmtN(PVB, 2)} บาท)`,
                bWins
                  ? `ควรเลือก <b>ข้อเสนอ A</b> เพราะได้รับเงินสดเร็วกว่า`
                  : `ควรเลือก <b>ข้อเสนอ B</b> เพราะยอดเงิน ${fmtN(Y, 0)} บาท สูงกว่า ${fmtN(X, 0)} บาท`
              ],
              answer: 0,
              shuffle: false,
              hint: `หามูลค่าปัจจุบันของข้อเสนอ B ด้วย $P = \\frac{${Y}}{(1+${i})^{${t}}}$ แล้วเทียบกับเงินสด ${fmtN(X, 0)} บาท`,
              why: bWins
                ? `มูลค่าปัจจุบันของ B (${fmtN(PVB, 2)} บาท) $>$ A (${fmtN(X, 0)} บาท) จึงควรเลือกข้อเสนอ B`
                : `เงินสด A (${fmtN(X, 0)} บาท) $>$ มูลค่าปัจจุบันของ B (${fmtN(PVB, 2)} บาท) จึงควรเลือกข้อเสนอ A`,
              verify: () => 0
            }));
          }

          return qs;
        }
      }
    ]
  };
})();
