  const MK = window.MK, Q = MK.Q;

  function fmtN(n, d = 0) {
    return Number(n).toLocaleString('en-US', { minimumFractionDigits: d, maximumFractionDigits: d });
  }

  function asum(a1, d, n) { return n * (2 * a1 + (n - 1) * d) / 2; }
  function gsum(a1, r, n) {
    let s = 0, t = a1;
    for (let i = 0; i < n; i++) { s += t; t *= r; }
    return s;
  }

