              label: `ข้อ ${idx + 1}`,
              q: `<b>สถานการณ์:</b> ${sc.story}<br><span class="muted">วิธีทำด้านล่างมีข้อผิดพลาด 1 จุด — จงแตะบรรทัดแรกที่ผิด เลือกสาเหตุ และพิมพ์คำตอบที่ถูกต้อง</span>`,
