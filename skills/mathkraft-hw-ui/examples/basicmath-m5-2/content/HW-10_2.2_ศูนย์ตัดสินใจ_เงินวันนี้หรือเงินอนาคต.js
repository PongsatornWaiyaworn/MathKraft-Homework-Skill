                  why: `$PV = ${fmtN(As[0] / (1 + i), 2)} + ${fmtN(As[1] / Math.pow(1 + i, 3), 2)} + ${fmtN(As[2] / Math.pow(1 + i, 5), 2)} = <b>${fmtN(PV, 2)}</b>$ บาท`,
                  verify: () => PV
